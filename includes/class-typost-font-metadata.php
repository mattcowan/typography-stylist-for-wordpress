    // Helpers
    // -----------------------------------------------------------------

    /**
     * Convert an OpenType Fixed (16.16, big-endian unsigned) to float.
     * Twin of Typost_Font_Parser::fixed_to_float() — duplicated on purpose.
     *
     * @param int $uint32 Unsigned 32-bit value from unpack('N').
     * @return float
     */
    private static function fixed_to_float($uint32) {
        if ($uint32 >= 0x80000000) {
            $uint32 -= 4294967296;
        }
        return $uint32 / 65536;
    }

    /**
     * Decode a UTF-16BE byte string to UTF-8, with a manual BMP-only
     * fallback when mbstring is unavailable.
     *
     * @param string $bytes
     * @return string
     */
    private static function utf16be_to_utf8($bytes) {
        if (function_exists('mb_convert_encoding')) {
            $converted = mb_convert_encoding($bytes, 'UTF-8', 'UTF-16BE');
            return ($converted === false) ? '' : $converted;
        }

        $result = '';
        $units = unpack('n*', substr($bytes, 0, strlen($bytes) - (strlen($bytes) % 2)));
        if ($units === false) {
            return '';
        }
        foreach ($units as $code) {
            if ($code >= 0xD800 && $code <= 0xDFFF) {
                continue; // Skip surrogates in the fallback path.
            }
            if ($code < 0x80) {
                $result .= chr($code);
            } elseif ($code < 0x800) {
                $result .= chr(0xC0 | ($code >> 6)) . chr(0x80 | ($code & 0x3F));
            } else {
                $result .= chr(0xE0 | ($code >> 12)) . chr(0x80 | (($code >> 6) & 0x3F)) . chr(0x80 | ($code & 0x3F));
            }
        }
        return $result;
    }

    /**
     * Decode a Latin-1-ish (Mac Roman approximation) byte string to UTF-8.
     *
     * @param string $bytes
     * @return string
     */
    private static function latin1_to_utf8($bytes) {
        $result = '';
        $length = strlen($bytes);
        for ($i = 0; $i < $length; $i++) {
            $code = ord($bytes[$i]);
            if ($code < 0x80) {
                $result .= $bytes[$i];
            } else {
                $result .= chr(0xC0 | ($code >> 6)) . chr(0x80 | ($code & 0x3F));
            }
        }
        return $result;
    }

    /**
     * Turn a filename fragment into a readable family name:
     * separators become spaces and camelCase words are split.
     *
     * @param string $fragment
     * @return string
     */
    private static function clean_filename_family($fragment) {
        $family = str_replace(array('_', '-'), ' ', $fragment);
        $family = preg_replace('/(?<=[a-z0-9])(?=[A-Z])/', ' ', $family);
        $family = preg_replace('/\s+/', ' ', $family);
        return trim($family);
    }

    /**
     * Sanitize a family name for embedding in a double-quoted CSS string.
     *
     * @param string $family
     * @return string
     */
    private static function sanitize_family($family) {
        if (!is_string($family)) {
            return '';
        }
        $family = str_replace(array('"', '\\'), '', $family);
        $family = preg_replace('/[\x00-\x1F\x7F]/', '', $family);
        $family = preg_replace('/\s+/', ' ', $family);
        return trim($family);
    }

    /**
     * Format a weight value (int or min/max range) for the font-weight
     * declaration, clamped to CSS's 1–1000 range.
     *
     * @param int|float|array $weight
     * @return string
     */
    private static function weight_to_css($weight) {
        if (is_array($weight) && isset($weight['min'], $weight['max'])) {
            return self::format_weight_number($weight['min']) . ' ' . self::format_weight_number($weight['max']);
        }
        return self::format_weight_number($weight);
    }

    /**
     * Clamp and format a single weight number, trimming trailing zeros.
     *
     * @param int|float $value
     * @return string
     */
    private static function format_weight_number($value) {
        if (!is_numeric($value)) {
            return '400';
        }
        $value = (float) $value;
        if ($value < 1) {
            $value = 1;
        } elseif ($value > 1000) {
            $value = 1000;
        }
        if ((float) (int) $value === $value) {
            return (string) (int) $value;
        }
        return rtrim(rtrim(number_format($value, 2, '.', ''), '0'), '.');
    }

    /**
     * CSS format() identifier for a file extension.
     *
     * @param string $ext         Lowercase file extension.
     * @param bool   $is_variable Whether the face is a variable font.
     * @return string
     */
    private static function format_string($ext, $is_variable) {
        $formats = array(
            'ttf'   => 'truetype',
            'otf'   => 'opentype',
            'woff'  => 'woff',
            'woff2' => 'woff2',
            'eot'   => 'embedded-opentype',
        );
        $format = isset($formats[$ext]) ? $formats[$ext] : 'truetype';
        if ($is_variable && $ext !== 'eot') {
            $format .= '-variations';
        }
        return $format;
    }

    /**
     * Path of a font file relative to the kit directory, URL-encoded per
     * segment (the pipeline's url() regexes reject unencoded whitespace).
     *
     * @param string $file          Absolute file path.
     * @param string $kit_base_path Kit directory.
     * @return string
     */
    private static function relative_url($file, $kit_base_path) {
        $file = str_replace('\\', '/', $file);
        $base = rtrim(str_replace('\\', '/', $kit_base_path), '/');

        if ($base !== '' && strpos($file, $base . '/') === 0) {
            $relative = substr($file, strlen($base) + 1);
        } else {
            $relative = basename($file);
        }

        return implode('/', array_map('rawurlencode', explode('/', $relative)));
    }
